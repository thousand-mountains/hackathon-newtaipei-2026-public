const S_ = (id, t, refs) => ({ id, t, refs: refs || [] })

function committeeBlocks() {
  return [{ ty: 'meta', text: COMMITTEE_HEAD }, { ty: 'gap' }, ...COMMITTEE.map((c) => ({ ty: 'meta', text: c }))]
}

