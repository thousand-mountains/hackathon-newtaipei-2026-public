// 版式 C：撤銷／撤銷另為處分（主文→事實→理由）
function docC(PROC) {
  const isRevoke = PROC.main === 1 // 「原處分撤銷。」單純撤銷，其餘為撤銷另處
  return [
    ...docHead(),
    { ty: 'gap' }, { ty: 'h', text: '主　文' },
    { ty: 'p', ss: [S_('m0', PROC_MAINS_C[PROC.main], ['proc', '訴81'])] },
    ...factSection(),
    { ty: 'gap' }, { ty: 'h', text: '理　由' },
    { ty: 'p', ss: [
      S_('r1', '一、按行政院及各級行政機關訴願審議委員會審議規則第26條第2項規定：「原行政處分機關逾期不為答辯或答辯不完備者，受理訴願機關得逕為決定；必要時，得撤銷原行政處分，命其於一定期間內另為適法之處分。」', ['審26']),
    ] },
    { ty: 'p', ss: [
      S_('r5', '二、卷查原處分機關答辯未具體記載違規事實過程，亦未檢附證據資料，致本件事實未臻明確，' + (isRevoke ? '原處分非無違誤，爰予撤銷，以符法制。' : '爰將原處分撤銷，由原處分機關查明後另為適法之處分，以資妥適。'), ['X4', '審26', 'C4']),
    ] },
    { ty: 'p', ss: [S_('r9', '三、綜上論結，本件訴願為有理由，依訴願法第81條第1項' + (isRevoke ? '' : '及第2項') + '規定，決定如主文。', ['訴81'])] },
    ...docTail(['訴81']),
  ]
}

