export function buildDOC(PROC) {
  return PROC.con === 'A' ? docA(PROC) : PROC.con === 'C' ? docC(PROC) : PROC.con === 'D' ? docD(PROC) : docB()
}

export function mainText(PROC) {
  if (PROC.con === 'A') return '訴願不受理。'
  if (PROC.con === 'B') return '訴願駁回。'
  if (PROC.con === 'C') return PROC_MAINS_C[PROC.main]
  return '原處分關於書面告誡部分，訴願駁回。<br>原處分關於限期改善部分，訴願不受理。'
}
